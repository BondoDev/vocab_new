import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compileTsToCommonJs } from "../../lib/compileTs.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..", "..", "..");

const TARGET_LANGUAGES = ["english", "german", "spanish", "french", "italian", "portuguese", "russian"];
const SUPPORTED_LEVELS = ["a1", "a2", "b1", "b2", "c1", "c2"];
const PREVIEW_DIR = path.join(rootDir, "src", "data", "seo", "vocabularyLevels", "level-browse-preview");

const expectedKeys = TARGET_LANGUAGES.flatMap((targetLanguage) =>
  SUPPORTED_LEVELS.map((level) => `${targetLanguage}-${level}`),
);

const actualFiles = fs
  .readdirSync(PREVIEW_DIR)
  .filter((name) => name.endsWith(".json"));
const actualKeys = actualFiles.map((name) => name.slice(0, -".json".length));

const missing = expectedKeys.filter((key) => !actualKeys.includes(key));
assert.deepEqual(missing, [], `missing level-browse-preview files: ${missing.join(", ")}`);

const unexpected = actualKeys.filter((key) => !expectedKeys.includes(key));
assert.deepEqual(
  unexpected,
  [],
  `unexpected/misnamed level-browse-preview files (not a supported language-level combination): ${unexpected.join(", ")}`,
);

const seenKeys = new Set();
for (const key of actualKeys) {
  assert.ok(!seenKeys.has(key), `duplicate level-browse-preview key: ${key}`);
  seenKeys.add(key);
}

const malformed = [];
for (const key of expectedKeys) {
  const filePath = path.join(PREVIEW_DIR, `${key}.json`);
  const [targetLanguage, level] = key.split(/-(?=[a-c][12]$)/);

  let data;
  try {
    data = JSON.parse(fs.readFileSync(filePath, "utf8").replace(/^﻿/, ""));
  } catch (error) {
    malformed.push(`${key}: invalid JSON (${error.message})`);
    continue;
  }

  if (typeof data?.targetLanguage !== "string" || data.targetLanguage !== targetLanguage) {
    malformed.push(`${key}: targetLanguage field mismatch (expected "${targetLanguage}", got "${data?.targetLanguage}")`);
  }
  if (typeof data?.level !== "string" || data.level.toLowerCase() !== level) {
    malformed.push(`${key}: level field mismatch (expected "${level}", got "${data?.level}")`);
  }
  if (typeof data?.totalWords !== "number" || data.totalWords <= 0) {
    malformed.push(`${key}: totalWords must be a positive number`);
  }
  if (typeof data?.totalPages !== "number" || data.totalPages <= 0) {
    malformed.push(`${key}: totalPages must be a positive number`);
  }
  if (!Array.isArray(data?.words) || data.words.length === 0) {
    malformed.push(`${key}: words must be a non-empty array`);
    continue;
  }

  const seenConceptIds = new Set();
  for (const word of data.words) {
    if (typeof word?.concept_id !== "string" || typeof word?.word_lemma !== "string") {
      malformed.push(`${key}: word entries must have string concept_id and word_lemma`);
      break;
    }
    if (seenConceptIds.has(word.concept_id)) {
      malformed.push(`${key}: duplicate concept_id "${word.concept_id}"`);
      break;
    }
    seenConceptIds.add(word.concept_id);
  }
}

assert.deepEqual(malformed, [], `malformed level-browse-preview data:\n${malformed.join("\n")}`);

// Freshness + route resolution. The preview files are generated by
// scripts/generation/generate-word-hub-data.mjs as the first browse page of
// each level's current vocabulary list; hand-maintained copies previously
// drifted from vocabulary.json and prerendered links to 410 word URLs. Each
// entry must therefore (1) match a fresh derivation from vocabulary.json and
// (2) resolve, for every UI language, through the same parser/lookup rules
// the word Worker applies (workers/word-ssr/src/index.full.ts) to a 200 page
// for that exact concept — not a 308 or 410.
const BROWSE_PAGE_SIZE = 54;
const UI_LANGUAGES = ["en", "es", "fr", "de", "it", "pt", "ru"];

const compiled = compileTsToCommonJs(".tmp-level-browse-preview-test", [
  path.join(rootDir, "src", "data", "seo", "wordPages", "wordRouteManifest.ts"),
  path.join(rootDir, "src", "data", "seo", "wordPages", "wordSlugs.ts"),
  path.join(rootDir, "src", "data", "seo", "wordPages", "verifiedHistoricalWordRouteRedirects.ts"),
  path.join(rootDir, "src", "data", "seo", "shared", "browseWordValidation.ts"),
]);

const stale = [];
const unresolved = [];
let checkedLinks = 0;
try {
  const { parseWordRoutePathname, wordToSlug } = compiled.require("src/data/seo/wordPages/wordRouteManifest");
  const { buildWordPath } = compiled.require("src/data/seo/wordPages/wordSlugs");
  const { VERIFIED_HISTORICAL_WORD_ROUTE_REDIRECTS } = compiled.require(
    "src/data/seo/wordPages/verifiedHistoricalWordRouteRedirects",
  );
  const { isValidBrowseWordLemma } = compiled.require("src/data/seo/shared/browseWordValidation");

  for (const targetLanguage of TARGET_LANGUAGES) {
    const vocabulary = JSON.parse(
      fs
        .readFileSync(path.join(rootDir, "src", "data", "vocabulary", targetLanguage, "vocabulary.json"), "utf8")
        .replace(/^﻿/, ""),
    );
    const recordsById = new Map(vocabulary.map((entry) => [entry.concept_id, entry]));

    for (const level of SUPPORTED_LEVELS) {
      const key = `${targetLanguage}-${level}`;
      const preview = JSON.parse(
        fs.readFileSync(path.join(PREVIEW_DIR, `${key}.json`), "utf8").replace(/^﻿/, ""),
      );

      // Same filter as VocabularyLevelPage's client-side browse list.
      const seen = new Set();
      const levelWords = [];
      for (const entry of vocabulary) {
        if (entry.level !== level.toUpperCase()) continue;
        if (!isValidBrowseWordLemma(entry.word_lemma) || seen.has(entry.concept_id)) continue;
        seen.add(entry.concept_id);
        levelWords.push(entry);
      }
      const expected = {
        targetLanguage,
        level: level.toUpperCase(),
        totalWords: levelWords.length,
        totalPages: Math.max(1, Math.ceil(levelWords.length / BROWSE_PAGE_SIZE)),
        words: levelWords
          .slice(0, BROWSE_PAGE_SIZE)
          .map((entry) => ({ concept_id: entry.concept_id, word_lemma: entry.word_lemma })),
      };
      try {
        assert.deepEqual(preview, expected);
      } catch {
        stale.push(`${key}: differs from vocabulary.json — run \`npm run generate:word-hub-data\``);
      }

      for (const word of preview.words) {
        const record = recordsById.get(word.concept_id);
        for (const uiLang of UI_LANGUAGES) {
          checkedLinks += 1;
          const href = buildWordPath(uiLang, targetLanguage, word.word_lemma, word.concept_id);
          const parsed = parseWordRoutePathname(href);
          const problem =
            parsed.kind !== "canonical"
              ? `parses as ${parsed.kind}`
              : !record
                ? "concept missing from vocabulary.json (Worker 410 missing-record)"
                : record.level !== parsed.conceptId.slice(0, 2)
                  ? "concept level does not match its ID prefix (Worker 410 missing-record)"
                  : wordToSlug(record.word_lemma) !== parsed.wordSlug
                    ? `slug "${parsed.wordSlug}" != current "${wordToSlug(record.word_lemma)}" (Worker 410 slug-mismatch)`
                    : targetLanguage === "english" &&
                        VERIFIED_HISTORICAL_WORD_ROUTE_REDIRECTS.has(`${parsed.conceptId}:${parsed.wordSlug}`)
                      ? "collides with a verified historical redirect (Worker 308)"
                      : null;
          if (problem) {
            unresolved.push(`${key} ${word.concept_id} "${word.word_lemma}" ${href}: ${problem}`);
          }
        }
      }
    }
  }
} finally {
  compiled.cleanup();
}

assert.deepEqual(stale, [], `stale level-browse-preview data:\n${stale.join("\n")}`);
assert.deepEqual(
  unresolved,
  [],
  `level-browse-preview links that the word Worker would not serve as 200:\n${unresolved.slice(0, 20).join("\n")}`,
);

console.log(
  `level browse preview completeness passed: ${expectedKeys.length} expected combinations, all present, well-formed, ` +
    `in sync with vocabulary.json, and ${checkedLinks} preview links resolve to their canonical word pages`,
);
