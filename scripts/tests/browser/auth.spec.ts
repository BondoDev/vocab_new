import { test, expect } from './practice-fixtures';
import { installMockBackend } from './mock-backend';

test.describe.configure({ timeout: 90_000 });

test('auth dialog validation, mocked errors, registration navigation and reset-email transition', async ({ page, mockApi }) => {
  installMockBackend(mockApi);
  await page.goto('/');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toHaveAccessibleName('Welcome back');
  await dialog.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Email is required');
  await dialog.getByLabel('Email', { exact: true }).fill('browser@example.invalid');
  await dialog.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Password is required');
  await dialog.getByLabel('Password', { exact: true }).fill('Browser-only-password1');
  await dialog.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Incorrect email or password');
  await dialog.getByRole('button', { name: 'Sign up', exact: true }).click();
  await expect(dialog).toHaveAccessibleName('Create your FluentStellar account');
  await dialog.getByLabel('Email', { exact: true }).fill('browser@example.invalid');
  await dialog.getByLabel('Password', { exact: true }).fill('short');
  await dialog.getByLabel('Confirm password', { exact: true }).fill('short');
  await dialog.getByRole('button', { name: 'Sign up', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('8');
  await dialog.getByLabel('Password', { exact: true }).fill('Browser-only-password1');
  await dialog.getByLabel('Confirm password', { exact: true }).fill('Different-password1');
  await dialog.getByRole('button', { name: 'Sign up', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Passwords do not match');
  await dialog.getByLabel('Confirm password', { exact: true }).fill('Browser-only-password1');
  await dialog.getByRole('button', { name: 'Sign up', exact: true }).click();
  await expect(dialog.getByRole('alert')).toBeVisible();
  await dialog.getByRole('button', { name: 'Log in', exact: true }).click();
  await dialog.getByLabel('Email', { exact: true }).fill('browser@example.invalid');
  await dialog.getByRole('button', { name: 'Forgot password?', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText(/reset|recovery/i);
  await expect.poll(() => mockApi.requests.filter((request) => request.startsWith('POST /auth/')).length).toBe(3);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
});

test('recovery cleans URL, suppresses incomplete-profile onboarding, handles rejection and completes', async ({ page, mockApi }) => {
  installMockBackend(mockApi, false);
  await page.goto('/?keep=1#error_description=ignored&type=recovery&access_token=browser-only-recovery&refresh_token=browser-only-refresh&expires_at=4102444800');
  const recovery = page.getByRole('dialog', { name: 'Set new password', exact: true });
  await expect(recovery).toBeVisible();
  await expect(page).toHaveURL('http://127.0.0.1:4173/?keep=1');
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'Cancel registration', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await expect(recovery).toBeVisible();
  await recovery.getByLabel('New password', { exact: true }).fill('short');
  await recovery.getByLabel('Confirm new password', { exact: true }).fill('short');
  await recovery.getByRole('button', { name: 'Save password', exact: true }).click();
  await expect(recovery.getByRole('alert')).toContainText('8');
  await recovery.getByLabel('New password', { exact: true }).fill('Browser-only-password1');
  await recovery.getByLabel('Confirm new password', { exact: true }).fill('Different-password1');
  await recovery.getByRole('button', { name: 'Save password', exact: true }).click();
  await expect(recovery.getByRole('alert')).toContainText('Passwords do not match');
  await recovery.getByLabel('Confirm new password', { exact: true }).fill('Browser-only-password1');
  await recovery.getByRole('button', { name: 'Save password', exact: true }).click();
  await expect(recovery.getByRole('alert')).toContainText('Mock password update rejected');
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await recovery.getByRole('button', { name: 'Save password', exact: true }).click();
  await expect(recovery.getByRole('status')).toContainText('Your password has been updated');
  await recovery.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(recovery).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Cancel registration', exact: true })).toBeVisible();
  await expect.poll(() => mockApi.requests.filter((request) => request === 'PUT /auth/v1/user').length).toBe(2);
});
